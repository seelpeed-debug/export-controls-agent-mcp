// PRC export-control framework, MOFCOM.
//
// HAND-TRANSCRIBED, NOT GENERATED. There is no versioned machine-readable source
// for this regime. MOFCOM publishes announcements (公告) as individual web pages
// and PDF attachments with no stable API, no issue-date index and no diff
// mechanism, so nothing here can be rebuilt the way the eCFR snapshots are. Every
// fact below carries the announcement or instrument it came from, and
// scripts/validate-china.mjs checks the volatile parts for drift.
//
// WHAT MAKES THIS REGIME DIFFERENT TO MODEL
//
// 1. The operative question is usually "is this measure currently in force?",
//    not "what does it say". Announcements Nos. 55, 56, 57, 58, 61 and 62 of 2025
//    were suspended by Announcement No. 70 of 2025 with a fixed end date. Saying
//    they apply today would be wrong; saying they are gone would also be wrong,
//    because the suspension expires and the instruments remain law. Status is
//    therefore computed against a date, and both facts travel together.
//
// 2. It reaches non-Chinese parties directly. Announcement No. 61 requires a
//    MOFCOM permit for shipments between two points that are both outside China,
//    and the 管控名单 designations prohibit parties in ANY country from supplying
//    Chinese-origin dual-use items to a listed entity. A Korean exporter with no
//    Chinese entity and no U.S. nexus can still be squarely inside this regime.
//
// 3. Its de minimis test runs the opposite way to the EAR's. § 734.4 gives a
//    ceiling you fall below to escape; No. 61 gives a floor you rise above to be
//    caught, and that floor is 0.1 percent of item value.
//
// CITATION DISCIPLINE
// Article numbers of the Export Control Law and the 2024 Regulations are
// deliberately NOT asserted here. They could not be verified to the standard the
// rest of this project uses, and a wrong article number is the defect class this
// project spent a release removing. Instruments are cited by name and effective
// date, announcements by number and date. Both were verified.

